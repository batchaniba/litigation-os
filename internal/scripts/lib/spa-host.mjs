// SPA host routing for Vercel (production) and Cloudflare Pages (Phase 1).
// One catalog: internal/public/short-links.json. Do not hand-maintain a
// second redirect list.
//
// Cloudflare Pages docs fetched 2026-09-21:
//   redirects: https://developers.cloudflare.com/pages/configuration/redirects/
//   headers:   https://developers.cloudflare.com/pages/configuration/headers/
//   routes:    https://developers.cloudflare.com/pages/functions/routing/
//   serving:   https://developers.cloudflare.com/pages/configuration/serving-pages/
//   build:     https://developers.cloudflare.com/pages/configuration/build-configuration/

import { DOCUMENTS_ORIGIN } from "./documents-origin.mjs";
import { vercelSpaRewrites } from "./documents-branch.mjs";

/** Dashboard project name → https://interactive-litigation-portfolio.pages.dev */
export const PAGES_PROJECT_NAME = "interactive-litigation-portfolio";
export const PAGES_DEV_HOST = `${PAGES_PROJECT_NAME}.pages.dev`;

/** Analogue of vercel.json `{ source: "/(.*)", destination: "/index.html" }`. */
export const PAGES_SPA_FALLBACK = "/* /index.html 200";

/** Pages `_headers` line budget (docs: 2,000 characters per line). */
export const PAGES_HEADER_LINE_LIMIT = 2000;

export function contentDisposition(downloadName) {
  const quoted = downloadName.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
  const encoded = encodeURIComponent(downloadName).replace(
    /[()]/g,
    (ch) => `%${ch.charCodeAt(0).toString(16).toUpperCase()}`,
  );
  return `attachment; filename="${quoted}"; filename*=UTF-8''${encoded}`;
}

export function buildVercelJson(links) {
  const redirects = [];
  const headers = [];
  for (const link of links) {
    const dest = `/${link.slug}.pdf`;
    redirects.push({ source: `/${link.slug}`, destination: dest, permanent: false });
    redirects.push({ source: `/${link.slug}/`, destination: dest, permanent: false });
    headers.push({
      source: dest,
      headers: [{ key: "Content-Disposition", value: contentDisposition(link.downloadName) }],
    });
  }
  return {
    $schema: "https://openapi.vercel.sh/vercel.json",
    // Production is deployed by the scheduled Deploy Hook
    // (internal/workers/vercel-deploy-cron/), not by every push to main.
    // Vercel reads this key from the committed file at push time, which is
    // why vercel.json is tracked even though this script regenerates it.
    // See internal/docs/VERCEL_DEPLOYS.md.
    git: { deploymentEnabled: false },
    redirects,
    headers,
    rewrites: vercelSpaRewrites(),
  };
}

/**
 * Cloudflare Pages `_redirects` (Netlify-style).
 *
 * Static short-link 302s first, then the dynamic SPA splat. `/documents/*` is
 * intentionally absent: a 200 rewrite to workers.dev is not supported
 * ("Proxying will only support relative URLs on your site").
 *
 * @param {Array<{ slug: string }>} links
 */
export function buildPagesRedirects(links) {
  const lines = [
    "# Generated by npm run sync:short-links from internal/public/short-links.json.",
    "# Do not hand-edit. Pages reads this from the build output (dist/), copied",
    "# from internal/public/ by Vite.",
    "#",
    "# https://developers.cloudflare.com/pages/configuration/redirects/",
    "#   - one rule per line: [source] [destination] [code?]",
    "#   - static redirects before dynamic (splats / placeholders)",
    "#   - 200 proxy is same-origin only; cannot point at workers.dev",
    "#   - /* /index.html 200 is the SPA analogue of vercel.json rewrites[1]",
    "# /documents/* → Worker is functions/documents/[[path]].js + _routes.json.",
    "",
  ];
  for (const link of links) {
    const dest = `/${link.slug}.pdf`;
    lines.push(`/${link.slug} ${dest} 302`);
    lines.push(`/${link.slug}/ ${dest} 302`);
  }
  lines.push("");
  lines.push("# Dynamic splat last. Pages also SPA-routes when 404.html is absent");
  lines.push("# (https://developers.cloudflare.com/pages/configuration/serving-pages/).");
  lines.push("# Do not add a top-level 404.html — that would disable built-in SPA fallback.");
  lines.push(PAGES_SPA_FALLBACK);
  lines.push("");
  return `${lines.join("\n")}`;
}

/**
 * Cloudflare Pages `_headers` for slug PDFs (Content-Disposition) plus
 * noindex on *.pages.dev so Phase 1 does not compete with Vercel production.
 *
 * @param {Array<{ slug: string, downloadName: string }>} links
 */
export function buildPagesHeaders(links) {
  const lines = [
    "# Generated by npm run sync:short-links from internal/public/short-links.json.",
    "# Do not hand-edit. https://developers.cloudflare.com/pages/configuration/headers/",
    "# Each line is capped at 2,000 characters; at most 100 header rules.",
    "#",
    "# Phase 1 host is *.pages.dev, not production. Keep it out of search indexes",
    "# until the Phase 3 custom-domain cutover (Vercel stays live).",
    "",
    `https://${PAGES_DEV_HOST}/*`,
    "  X-Robots-Tag: noindex",
    "",
    `https://:version.${PAGES_DEV_HOST}/*`,
    "  X-Robots-Tag: noindex",
    "",
  ];
  for (const link of links) {
    const dest = `/${link.slug}.pdf`;
    const headerLine = `  Content-Disposition: ${contentDisposition(link.downloadName)}`;
    if (headerLine.length > PAGES_HEADER_LINE_LIMIT) {
      throw new Error(
        `Pages _headers line exceeds ${PAGES_HEADER_LINE_LIMIT} chars for ${link.slug} (${headerLine.length})`,
      );
    }
    lines.push(dest);
    lines.push(headerLine);
    lines.push("");
  }
  return lines.join("\n");
}

/**
 * Limit Pages Functions invocations to the documents proxy.
 * Without this, adding `functions/` bills every static request.
 * https://developers.cloudflare.com/pages/functions/routing/
 */
export function buildPagesRoutesJson() {
  return {
    version: 1,
    include: ["/documents/*"],
    exclude: [],
  };
}

